def crear_tensor_numpy(alto, ancho, marco=True):
    """Crea un mapa NumPy con (alto, ancho, 6) capas uint8."""
    if alto < 3 or ancho < 3:
        raise ValueError("El mapa debe medir al menos 3 x 3.")
    t = np.zeros((int(alto), int(ancho), CAPAS), dtype=np.uint8)
    if marco:
        t[0, :, CAPA_FISICA] = MURO
        t[-1, :, CAPA_FISICA] = MURO
        t[:, 0, CAPA_FISICA] = MURO
        t[:, -1, CAPA_FISICA] = MURO
    return t


def colocar_numpy(t, y, x, estado):
    """Usa la convencion fila = y, columna = x."""
    t[int(y), int(x), CAPA_FISICA] = estado


def contar_numpy(t):
    """Conteos de entidades; acepta NumPy y CuPy."""
    f = t[:, :, CAPA_FISICA]
    n = lambda e: int((f == e).sum().item())
    return {
        "obreras_n": n(OBRERA_N), "soldados_n": n(SOLDADO_N),
        "obreras_r": n(OBRERA_R), "soldados_r": n(SOLDADO_R),
        "depredadores": n(DEPREDADOR), "cadaveres": n(CADAVER),
        "veneno": n(VENENO), "comida": n(COMIDA),
        "celdas_rastro_comida": int((t[:, :, CAPA_RASTRO_COMIDA] > 0).sum().item()),
        "celdas_alarma": int((t[:, :, CAPA_ALARMA] > 0).sum().item()),
    }


class MotorNumPy:
    """Motor NUMPY con doble búfer y reglas vectorizadas.

    Acceso: motor.actual / motor.siguiente; motor.avanzar_tick().
    El objeto `api` (ModoDios) es opcional; se procesa ANTES de cada tick.
    """

    def __init__(self, alto=500, ancho=500, semilla=7, api=None,
                 prob_expansion_veneno=PROB_EXPANSION_VENENO,
                 fraccion_maxima_veneno=FRACCION_MAXIMA_VENENO,
                 prob_movimiento_depredador=PROB_MOVIMIENTO_DEPREDADOR,
                 prob_muerte_veneno=PROB_MUERTE_VENENO,
                 prob_movimiento_arena=PROB_MOVIMIENTO_ARENA,
                 prob_retorno_real=PROB_RETORNO_REAL,
                 radio_radar_depredador=RADIO_RADAR_DEPREDADOR,
                 prob_ataque_depredador=PROB_ATAQUE_DEPREDADOR,
                 radio_busqueda_comida=RADIO_BUSQUEDA_COMIDA,
                 reserva_inicial=RESERVA_INICIAL, consumo_nido=CONSUMO_NIDO,
                 valor_comida=VALOR_COMIDA, costo_nacimiento=COSTO_NACIMIENTO,
                 limite_hambre=LIMITE_HAMBRE, prob_nacimiento=PROB_NACIMIENTO):
        from scipy.ndimage import maximum_filter
        xp = np
        self.xp = np
        self.backend = "numpy"
        self.usa_gpu = False
        self._maximum_filter = maximum_filter
        self.aleatorio = xp.random.RandomState(semilla)
        self.alto = int(alto)
        self.ancho = int(ancho)
        if min(self.alto, self.ancho) < 3:
            raise ValueError("El mapa debe medir al menos 3 x 3.")
        self.actual = xp.zeros((self.alto, self.ancho, CAPAS), dtype=xp.uint8)
        self.siguiente = xp.zeros_like(self.actual)
        self.actual[0, :, 0] = MURO
        self.actual[-1, :, 0] = MURO
        self.actual[:, 0, 0] = MURO
        self.actual[:, -1, 0] = MURO
        self.tick = 0
        self.simulacion = True
        self.api = api
        self.prob_expansion_veneno = float(prob_expansion_veneno)
        self.fraccion_maxima_veneno = float(fraccion_maxima_veneno)
        self.prob_movimiento_depredador = float(prob_movimiento_depredador)
        self.prob_muerte_veneno = float(prob_muerte_veneno)
        self.prob_movimiento_arena = float(prob_movimiento_arena)
        self.prob_retorno_real = float(prob_retorno_real)
        self.radio_radar_depredador = int(radio_radar_depredador)
        self.terreno_arena = xp.zeros((self.alto, self.ancho), dtype=bool)
        for nombre, valor in (
            ("prob_expansion_veneno", self.prob_expansion_veneno),
            ("fraccion_maxima_veneno", self.fraccion_maxima_veneno),
            ("prob_movimiento_depredador", self.prob_movimiento_depredador),
            ("prob_muerte_veneno", self.prob_muerte_veneno),
            ("prob_movimiento_arena", self.prob_movimiento_arena),
            ("prob_retorno_real", self.prob_retorno_real),
        ):
            if not 0 <= valor <= 1:
                raise ValueError(f"{nombre} debe estar entre 0 y 1.")
        if not 1 <= self.radio_radar_depredador <= 32:
            raise ValueError("radio_radar_depredador debe estar entre 1 y 32")
        self.prob_ataque_depredador = float(prob_ataque_depredador)
        self.prob_nacimiento = float(prob_nacimiento)
        self.radio_busqueda_comida = int(radio_busqueda_comida)
        self.reserva_inicial = float(reserva_inicial)
        self.consumo_nido = float(consumo_nido)
        self.valor_comida = float(valor_comida)
        self.costo_nacimiento = float(costo_nacimiento)
        self.limite_hambre = int(limite_hambre)
        for nombre, valor in (("prob_ataque_depredador", self.prob_ataque_depredador),
                              ("prob_nacimiento", self.prob_nacimiento)):
            if not 0 <= valor <= 1:
                raise ValueError(f"{nombre} debe estar entre 0 y 1.")
        for nombre, valor in (("reserva_inicial", self.reserva_inicial),
                              ("consumo_nido", self.consumo_nido),
                              ("valor_comida", self.valor_comida)):
            if not np.isfinite(valor) or valor < 0:
                raise ValueError(f"{nombre} debe ser finito y no negativo.")
        if not np.isfinite(self.costo_nacimiento) or self.costo_nacimiento <= 0:
            raise ValueError("costo_nacimiento debe ser positivo y finito.")
        if self.radio_busqueda_comida < 1 or self.limite_hambre < 1:
            raise ValueError("radio_busqueda_comida y limite_hambre deben ser positivos.")
        self.tabla_evaporacion = xp.maximum(
            xp.arange(256, dtype=xp.int16) - PERDIDA_EVAPORACION, 0
        ).astype(xp.uint8)
        self.kernels = (
            xp.asarray([[0, 10, 0], [10, 60, 10], [0, 10, 0]], dtype=xp.int32),
            xp.asarray([[0, 20, 0], [20, 20, 20], [0, 20, 0]], dtype=xp.int32),
            xp.asarray([[0, 5, 0], [5, 80, 5], [0, 5, 0]], dtype=xp.int32),
            xp.asarray([[0, 10, 0], [10, 60, 10], [0, 10, 0]], dtype=xp.int32),
            xp.asarray([[0, 10, 0], [10, 60, 10], [0, 10, 0]], dtype=xp.int32),
        )
        self._vecinos_kernel = {}
        for kernel in self.kernels:
            vecinos = []
            for dy, dx in DESPLAZAMIENTOS:
                peso = int(self._escalar(kernel[dy + 1, dx + 1]))
                if peso > 0:
                    vecinos.append((dy, dx, max(4, 12 - peso // 2)))
            self._vecinos_kernel[id(kernel)] = vecinos
        self._iniciar_estado_biologico()


    def _escalar(self, v):
        return v.item() if hasattr(v, "item") else v

    def _tiene(self, mascara):
        return bool(self._escalar(mascara.any()))

    def trasladar(self, a, dy, dx, relleno=0):
        """Desplaza sin conectar extremos, a diferencia de np.roll / cp.roll."""
        alto, ancho = a.shape[:2]
        salida = self.xp.full_like(a, relleno)
        ys0, ys1 = max(0, -dy), min(alto, alto - dy)
        xs0, xs1 = max(0, -dx), min(ancho, ancho - dx)
        if ys0 < ys1 and xs0 < xs1:
            salida[ys0 + dy:ys1 + dy, xs0 + dx:xs1 + dx] = a[ys0:ys1, xs0:xs1]
        return salida

    def escanear_presencia_3x3(self, mascara):
        """Vecindad de Moore sin efecto toroidal; no incluye celda central."""
        salida = self.xp.zeros_like(mascara, dtype=bool)
        for dy, dx in DESPLAZAMIENTOS:
            salida |= self.trasladar(mascara, dy, dx)
        return salida

    def escanear_gradiente_quimico(self, capa):
        """Sigue solo mejoras del olor; un máximo o una meseta no atraen."""
        xp = self.xp
        vecinos = xp.stack([self.trasladar(capa, -dy, -dx)
                            for dy, dx in DESPLAZAMIENTOS])
        maximo = vecinos.max(axis=0)
        # El azar actúa solo entre máximos iguales, sin redondeos en float32.
        desempate = self.aleatorio.random_sample(vecinos.shape)
        puntajes = xp.where(vecinos == maximo, desempate, -1.0)
        direccion = puntajes.argmax(axis=0).astype(xp.int8)
        mejora = xp.where(maximo > capa, maximo, 0)
        return direccion, mejora

    def difundir(self, capa, kernel, libres=None):
        """Propaga una señal con pérdida espacial, sin diluirla hasta cero.

        El kernel conserva sus direcciones y su velocidad relativa. El máximo
        representa alcance de olor, no conservación de masa de un fluido.
        Se trabaja en int16 para evitar el desbordamiento de uint8 al restar.
        """
        xp = self.xp
        if libres is None:
            libres = self.actual[:, :, CAPA_FISICA] != MURO
        salida = capa.astype(xp.int16) * libres
        for _ in range(PASOS_DIFUSION):
            anterior = salida
            salida = anterior.copy()
            for dy, dx, perdida in self._pasos_kernel(kernel):
                vecina = self.trasladar(anterior, dy, dx) - perdida
                salida = xp.maximum(salida, vecina)
            salida = xp.maximum(salida, 0) * libres
        return salida.astype(xp.uint8)

    def escanear_radar_presas(self, capa, radio=RADIO_RADAR_DEPREDADOR):
        """Radar del modelo biologico v6: alcance de 8 casillas, sin bordes toroidales.

        El mapa de calor se propaga en vecindad de Moore; los muros detienen
        la propagacion. Solo se llama si existen depredadores y presas.
        """
        xp = self.xp
        presas = ((capa == OBRERA_N) | (capa == SOLDADO_N) |
                  (capa == OBRERA_R) | (capa == SOLDADO_R))
        if not self._tiene(presas):
            return None, None
        muros = capa == MURO
        onda = presas
        mapa_calor = presas.astype(xp.uint8) * (radio + 1)
        for distancia in range(1, radio + 1):
            onda = self._maximum_filter(onda.astype(xp.uint8), size=3,
                                         mode="constant", cval=0) > 0
            onda &= ~muros
            mapa_calor = xp.maximum(mapa_calor,
                                    onda.astype(xp.uint8) * (radio + 1 - distancia))
        direccion, _ = self.escanear_gradiente_quimico(mapa_calor)
        # La presencia se mide en la celda del cazador; evita el error de
        # alcance de radio+1 ocasionado al mirar un vecino adicional.
        return direccion, mapa_calor

    def _movimiento_vectorizado(self, capa, direcciones, mascara_origen, permite_presas=False):
        """Mueve cada entidad una vez y transporta su carga y su memoria.

        Las colisiones reservan el destino. Atacar es una regla separada:
        el desplazamiento nunca elimina una presa.
        """
        xp = self.xp
        original = capa.copy()
        salida = original.copy()
        usados = xp.zeros(capa.shape, dtype=bool)
        reservados = xp.zeros(capa.shape, dtype=bool)
        victimas = xp.zeros(capa.shape, dtype=bool)
        if not self._tiene(mascara_origen):
            return usados, reservados, victimas
        carga_original = self.carga_comida.copy()
        pasos_original = self.pasos_con_carga.copy()
        exploracion = self._elegir_exploracion(original)
        # Si el rumbo preferido está bloqueado, se toma una salida disponible.
        libres = (original == VACIO) | (original == ARENA_SECA)
        preferida_libre = xp.zeros(capa.shape, dtype=bool)
        for indice, (dy, dx) in enumerate(DESPLAZAMIENTOS):
            preferida_libre |= ((direcciones == indice)
                                & self.trasladar(libres, -dy, -dx, False))
        direcciones = xp.where(preferida_libre, direcciones, exploracion)
        orden = self.aleatorio.permutation(8)
        if self.usa_gpu:
            orden = xp.asnumpy(orden)
        for indice in orden:
            indice = int(indice)
            dy, dx = DESPLAZAMIENTOS[indice]
            origen = mascara_origen & (direcciones == indice) & ~usados
            destino_libre = self.trasladar(libres & ~reservados, -dy, -dx, False)
            validos = origen & destino_libre
            arena = self.trasladar(self.terreno_arena, -dy, -dx, False)
            if self.prob_movimiento_arena < 1:
                validos &= (~arena | (self.aleatorio.random_sample(capa.shape)
                                      < self.prob_movimiento_arena))
            destinos = self.trasladar(validos, dy, dx, False)
            salida[validos] = xp.where(self.terreno_arena[validos], ARENA_SECA, VACIO)
            salida[destinos] = self.trasladar(original, dy, dx)[destinos]
            self.carga_comida[validos] = False
            self.carga_comida[destinos] = self.trasladar(carga_original, dy, dx)[destinos]
            self.pasos_con_carga[validos] = 0
            self.pasos_con_carga[destinos] = self.trasladar(pasos_original, dy, dx)[destinos]
            self.direccion_anterior[validos] = -1
            self.direccion_anterior[destinos] = indice
            usados |= validos
            reservados |= destinos
        capa[:] = salida
        return usados, reservados, victimas

    def mover_depredadores(self, capa, alarma, prob_movimiento=None):
        """La araña persigue presas, pero no mata por ocupar su casilla."""
        xp = self.xp
        depredadores = capa == DEPREDADOR
        if not self._tiene(depredadores):
            return
        prob = self.prob_movimiento_depredador if prob_movimiento is None else float(prob_movimiento)
        if not 0 <= prob <= 1:
            raise ValueError("prob_movimiento debe estar entre 0 y 1")
        azar = self._elegir_exploracion(capa)
        rumbo, intensidad = self.escanear_radar_presas(capa, self.radio_radar_depredador)
        direcciones = xp.where(intensidad > 0, rumbo, azar) if rumbo is not None else azar
        candidatos = depredadores & (self.aleatorio.random_sample(capa.shape) < prob)
        _, destinos, _ = self._movimiento_vectorizado(capa, direcciones, candidatos)
        alarma[depredadores | destinos] = 255

    def aplicar_regla_depredador(self, capa, alarma):
        """Alcance 3x3: cuatro soldados la abaten; cada araña ataca a una presa."""
        xp = self.xp
        aranas = capa == DEPREDADOR
        if not self._tiene(aranas):
            return
        soldados = ((capa == SOLDADO_N) | (capa == SOLDADO_R)).astype(xp.int8)
        cantidad = xp.zeros(capa.shape, dtype=xp.int8)
        for dy, dx in DESPLAZAMIENTOS:
            cantidad += self.trasladar(soldados, dy, dx)
        abatidas = aranas & (cantidad >= MIN_SOLDADOS_CONTRA_ARANA)
        capa[abatidas] = CADAVER
        vivas = aranas & ~abatidas
        pendientes = vivas & (self.aleatorio.random_sample(capa.shape)
                              < self.prob_ataque_depredador)
        orden = self.aleatorio.permutation(8)
        if self.usa_gpu:
            orden = xp.asnumpy(orden)
        for indice in orden:
            dy, dx = DESPLAZAMIENTOS[int(indice)]
            hormigas = ((capa == OBRERA_N) | (capa == OBRERA_R)
                        | (capa == SOLDADO_N) | (capa == SOLDADO_R))
            atacantes = pendientes & self.trasladar(hormigas, -dy, -dx, False)
            muertas = self.trasladar(atacantes, dy, dx, False)
            capa[muertas] = CADAVER
            alarma[muertas] = 255
            pendientes &= ~atacantes
        zona = vivas | self.escanear_presencia_3x3(vivas)
        alarma[(zona & (capa != MURO)) | abatidas] = 255

    def aplicar_regla_combate(self, capa, alarma):
        n = ((capa == SOLDADO_N) | (capa == OBRERA_N))
        r = ((capa == SOLDADO_R) | (capa == OBRERA_R))
        mueren_n = n & self.escanear_presencia_3x3(capa == SOLDADO_R)
        mueren_r = r & self.escanear_presencia_3x3(capa == SOLDADO_N)
        combate = mueren_n | mueren_r
        capa[combate] = CADAVER
        alarma[combate] = 255

    def aplicar_regla_veneno(self, capa, alarma, prob_muerte=None, prob_expansion=None):
        """Veneno mas lento y con limite REAL de ocupacion total."""
        xp = self.xp
        muerte = self.prob_muerte_veneno if prob_muerte is None else prob_muerte
        expansion = self.prob_expansion_veneno if prob_expansion is None else prob_expansion
        mascara = capa == VENENO
        if not self._tiene(mascara):
            return
        zona = self.escanear_presencia_3x3(mascara)
        victimas_veneno = ((capa == OBRERA_N) | (capa == SOLDADO_N) | (capa == REINA_N) |
                    (capa == OBRERA_R) | (capa == SOLDADO_R) | (capa == REINA_R)
                    | (capa == DEPREDADOR))
        muertas = zona & victimas_veneno & (self.aleatorio.random_sample(capa.shape) < muerte)
        capa[muertas] = CADAVER
        alarma[muertas] = 255

        limite = int(capa.size * self.fraccion_maxima_veneno)
        disponibles = max(0, limite - int(self._escalar(mascara.sum())))
        if disponibles == 0 or expansion == 0:
            return
        terreno = (capa == VACIO) | (capa == ARENA_SECA)
        candidatos = zona & terreno & (self.aleatorio.random_sample(capa.shape) < expansion)
        cantidad = int(self._escalar(candidatos.sum()))
        if cantidad > disponibles:
            indices = xp.flatnonzero(candidatos)
            elegidos = self.aleatorio.choice(indices, size=disponibles, replace=False)
            capa.reshape(-1)[elegidos] = VENENO
        else:
            capa[candidatos] = VENENO

    def aplicar_emision_inmutables(self, capa, real, necro, comida, reclutamiento):
        xp = self.xp
        real[(capa == REINA_N) | (capa == REINA_R)] = 255
        necro[capa == CADAVER] = 255
        # Antes solo se depositaba olor al comer; aqui la fuente emite cada tick.
        comida[capa == COMIDA] = 255
        reclutamiento[capa == BASURERO] = 255

    def aplicar_recoleccion_comida(self, capa, comida):
        """Cada obrera libre toma como máximo una celda de comida por turno."""
        xp = self.xp
        libres = ((capa == OBRERA_N) | (capa == OBRERA_R)) & ~self.carga_comida
        orden = self.aleatorio.permutation(8)
        if self.usa_gpu:
            orden = xp.asnumpy(orden)
        for indice in orden:
            dy, dx = DESPLAZAMIENTOS[int(indice)]
            toman = libres & self.trasladar(capa == COMIDA, -dy, -dx, False)
            recogida = self.trasladar(toman, dy, dx, False)
            capa[recogida] = xp.where(self.terreno_arena[recogida], ARENA_SECA, VACIO)
            self.carga_comida[toman] = True
            self.pasos_con_carga[toman] = 0
            libres &= ~toman

    def aplicar_limpieza_cadaveres(self, capa, reclutamiento):
        obreras = (capa == OBRERA_N) | (capa == OBRERA_R)
        limpieza = (capa == CADAVER) & self.escanear_presencia_3x3(obreras)
        capa[limpieza] = self.xp.where(self.terreno_arena[limpieza], ARENA_SECA, VACIO)
        reclutamiento[limpieza] = 255

    def aplicar_generacion_nidos(self, capa):
        """Un nacimiento posible por nido y turno, con reina viva y reservas."""
        xp = self.xp
        for nido, reina, obrera, soldado in (
                (NIDO_N, REINA_N, OBRERA_N, SOLDADO_N),
                (NIDO_R, REINA_R, OBRERA_R, SOLDADO_R)):
            if not self._tiene(capa == reina):
                continue
            cupo = int(self.reservas_nido[nido] // self.costo_nacimiento)
            if cupo < 1:
                continue
            candidatos = ((capa == nido)
                           & (self.aleatorio.random_sample(capa.shape) < self.prob_nacimiento))
            indices = xp.flatnonzero(candidatos)
            if indices.size > cupo:
                elegidos = self.aleatorio.choice(indices, size=cupo, replace=False)
                candidatos[:] = False
                candidatos.reshape(-1)[elegidos] = True
            orden = self.aleatorio.permutation(8)
            if self.usa_gpu:
                orden = xp.asnumpy(orden)
            for indice in orden:
                dy, dx = DESPLAZAMIENTOS[int(indice)]
                generan = candidatos & self.trasladar(capa == VACIO, -dy, -dx, False)
                nacen = self.trasladar(generan, dy, dx, False)
                es_soldado = self.aleatorio.random_sample(capa.shape) < FRACCION_SOLDADOS
                capa[nacen & ~es_soldado] = obrera
                capa[nacen & es_soldado] = soldado
                self.reservas_nido[nido] -= int(self._escalar(nacen.sum())) * self.costo_nacimiento
                candidatos &= ~generan

    def aplicar_movimiento(self, capa, dir_comida, dir_alarma):
        mascara = ((capa == OBRERA_N) | (capa == OBRERA_R) |
                   (capa == SOLDADO_N) | (capa == SOLDADO_R))
        obreras = (capa == OBRERA_N) | (capa == OBRERA_R)
        direcciones = self.xp.where(obreras, dir_comida, dir_alarma)
        self._movimiento_vectorizado(capa, direcciones, mascara)

    def aplicar_reglas_biologicas(self, lectura, escritura):
        """Resuelve una vez cada interacción, usando la química ya propagada."""
        xp = self.xp
        cf = escritura[:, :, CAPA_FISICA]
        cc = escritura[:, :, CAPA_RASTRO_COMIDA]
        ca = escritura[:, :, CAPA_ALARMA]
        cr = escritura[:, :, CAPA_FEROMONA_REAL]
        cn = escritura[:, :, CAPA_NECROFEROMONAS]
        crec = escritura[:, :, CAPA_RECLUTAMIENTO]

        self.aplicar_regla_veneno(cf, ca)
        self.aplicar_regla_depredador(cf, ca)
        self.aplicar_regla_combate(cf, ca)
        self._limpiar_estado_entidades(cf)
        self.aplicar_recoleccion_comida(cf, cc)
        self._entregar_comida(cf)
        self._dejar_rastro_de_regreso(cc)
        self.mover_depredadores(cf, ca)

        exploracion = self._elegir_exploracion(cf)
        dir_comida, max_comida = self.escanear_gradiente_quimico(cc)
        dir_necro, max_necro = self.escanear_gradiente_quimico(cn)
        dir_alarma, max_alarma = self.escanear_gradiente_quimico(ca)
        dir_recluta, max_recluta = self.escanear_gradiente_quimico(crec)
        dist_comida = self._distancias_hasta(
            cf, cf == COMIDA, "comida", radio=self.radio_busqueda_comida)
        dir_radar, hay_comida = self._rumbo_por_distancia(dist_comida)
        hay_comida &= dist_comida <= self.radio_busqueda_comida
        inversas = xp.asarray((1, 0, 3, 2, 7, 6, 5, 4), dtype=xp.int8)
        anterior = self.direccion_anterior
        regreso = xp.where(anterior >= 0, inversas[xp.maximum(anterior, 0)], -1)
        seguir_olor = (max_comida > 0) & (dir_comida != regreso)
        rumbo_obreras = xp.where(hay_comida, dir_radar,
                          xp.where(seguir_olor, dir_comida,
                            xp.where(max_necro > 0, dir_necro,
                              xp.where(max_recluta > 0, dir_recluta, exploracion))))
        rumbo_obreras = xp.where(self.carga_comida, exploracion, rumbo_obreras)
        rumbo_soldados = xp.where(max_alarma > 0, dir_alarma,
                           xp.where(max_recluta > 0, dir_recluta, exploracion))
        for nido, reina, obrera in ((NIDO_N, REINA_N, OBRERA_N),
                                    (NIDO_R, REINA_R, OBRERA_R)):
            hogar = (cf == nido) | (cf == reina)
            if not self._tiene(hogar):
                continue
            distancias = self._distancias_hasta(cf, hogar, f"hogar_{nido}")
            dir_hogar, hay_camino = self._rumbo_por_distancia(distancias)
            propias = cf == obrera
            retorno_ocasional = (propias & ~self.carga_comida & hay_camino
                                & ~hay_comida & (max_comida == 0)
                                & (max_necro == 0) & (max_recluta == 0)
                                & (cr > 0) & (self.aleatorio.random_sample(cf.shape)
                                              < self.prob_retorno_real))
            # La carga tiene prioridad absoluta sobre cualquier olor de comida.
            regresan = (propias & self.carga_comida & hay_camino) | retorno_ocasional
            rumbo_obreras = xp.where(regresan, dir_hogar, rumbo_obreras)
        self.aplicar_movimiento(cf, rumbo_obreras, rumbo_soldados)
        self._entregar_comida(cf)
        self.aplicar_limpieza_cadaveres(cf, crec)
        self.aplicar_mantenimiento_nidos(cf)
        self.aplicar_generacion_nidos(cf)
        self.aplicar_emision_inmutables(cf, cr, cn, cc, crec)
        self._limpiar_estado_entidades(cf)
        cf[0, :] = cf[-1, :] = MURO
        cf[:, 0] = cf[:, -1] = MURO
        escritura[:, :, 1:CAPAS] *= (cf != MURO)[:, :, None]

    def avanzar_tick(self):
        """Procesa pinceles, emite fuentes, propaga olores y resuelve la biología."""
        if not self.simulacion:
            return self.actual
        xp = self.xp
        if self.api is not None:
            self.api.procesar_cola_acciones(
                self.actual, terreno_arena=self.terreno_arena,
                estado_entidades=(self.carga_comida, self.pasos_con_carga,
                                  self.direccion_anterior))
        cf = self.actual[:, :, CAPA_FISICA]
        self.terreno_arena |= cf == ARENA_SECA
        self.terreno_arena[0, :] = self.terreno_arena[-1, :] = False
        self.terreno_arena[:, 0] = self.terreno_arena[:, -1] = False
        cf[0, :] = cf[-1, :] = MURO
        cf[:, 0] = cf[:, -1] = MURO
        self._limpiar_estado_entidades(cf)
        xp.copyto(self.siguiente, self.actual)
        self.aplicar_emision_inmutables(
            cf, self.siguiente[:, :, CAPA_FEROMONA_REAL],
            self.siguiente[:, :, CAPA_NECROFEROMONAS],
            self.siguiente[:, :, CAPA_RASTRO_COMIDA],
            self.siguiente[:, :, CAPA_RECLUTAMIENTO])
        libres = cf != MURO
        for indice, kernel in enumerate(self.kernels, start=1):
            evaporada = self.tabla_evaporacion[self.siguiente[:, :, indice]]
            self.siguiente[:, :, indice] = self.difundir(evaporada, kernel, libres)
        self.aplicar_reglas_biologicas(self.actual, self.siguiente)
        # Se mantiene la referencia pública para no invalidar las vistas del frontend.
        xp.copyto(self.actual, self.siguiente)
        self.tick += 1
        return self.actual

    def cargar_mapa(self, tensor):
        if tensor.shape != self.actual.shape:
            raise ValueError(f"Mapa de forma {tensor.shape}; esperado {self.actual.shape}.")
        xp = self.xp
        xp.copyto(self.actual, xp.asarray(tensor, dtype=xp.uint8))
        cf = self.actual[:, :, CAPA_FISICA]
        cf[0, :] = cf[-1, :] = MURO
        cf[:, 0] = cf[:, -1] = MURO
        self.siguiente[:] = 0
        self.terreno_arena[:] = cf == ARENA_SECA
        self._iniciar_estado_biologico()
        self.tick = 0

    def snapshot_cpu(self):
        """Transfiere a CPU solo cuando el frontend lo solicita."""
        return self.actual.copy()

    def apagar(self):
        self.simulacion = False

    def _iniciar_estado_biologico(self):
        """La carga y la memoria viajan con la hormiga, fuera de las seis capas."""
        xp = self.xp
        forma = (self.alto, self.ancho)
        self.carga_comida = xp.zeros(forma, dtype=bool)
        self.pasos_con_carga = xp.zeros(forma, dtype=xp.uint16)
        self.direccion_anterior = xp.full(forma, -1, dtype=xp.int8)
        self.reservas_nido = {NIDO_N: self.reserva_inicial, NIDO_R: self.reserva_inicial}
        self.turnos_hambre = {NIDO_N: 0, NIDO_R: 0}
        self.comida_entregada = {NIDO_N: 0, NIDO_R: 0}
        self._cache_distancias = {}

    def _limpiar_estado_entidades(self, capa):
        obreras = (capa == OBRERA_N) | (capa == OBRERA_R)
        moviles = (obreras | (capa == SOLDADO_N) | (capa == SOLDADO_R)
                   | (capa == DEPREDADOR))
        self.carga_comida &= obreras
        self.pasos_con_carga[~self.carga_comida] = 0
        self.direccion_anterior[~moviles] = -1

    def _pasos_kernel(self, kernel):
        # Se cachean los pesos para no sincronizar GPU en cada difusión.
        return self._vecinos_kernel[id(kernel)]

    def _distancias_hasta(self, capa, fuentes, clave, radio=None):
        """Distancia por caminos transitables; se recalcula solo si cambia el mapa."""
        xp = self.xp
        transitable = ((capa == VACIO) | (capa == ARENA_SECA)
                       | (capa == OBRERA_N) | (capa == OBRERA_R)
                       | (capa == SOLDADO_N) | (capa == SOLDADO_R)
                       | (capa == DEPREDADOR) | fuentes)
        guardado = self._cache_distancias.get(clave)
        if (guardado is not None
                and bool(self._escalar(xp.array_equal(guardado[0], fuentes)))
                and bool(self._escalar(xp.array_equal(guardado[1], transitable)))):
            return guardado[2]
        infinito = self.alto * self.ancho + 1
        distancias = xp.full(capa.shape, infinito, dtype=xp.int32)
        distancias[fuentes] = 0
        frontera = fuentes.copy()
        limite = infinito if radio is None else radio + 1
        for distancia in range(1, limite):
            if not self._tiene(frontera):
                break
            vecinas = self._maximum_filter(frontera, size=3, mode="constant", cval=0)
            frontera = vecinas & transitable & (distancias == infinito)
            distancias[frontera] = distancia
        self._cache_distancias[clave] = (fuentes.copy(), transitable.copy(), distancias)
        return distancias

    def _rumbo_por_distancia(self, distancias):
        """Devuelve una dirección que acerca a una fuente alcanzable."""
        xp = self.xp
        infinito = self.alto * self.ancho + 1
        vecinos = xp.stack([self.trasladar(distancias, -dy, -dx, infinito)
                            for dy, dx in DESPLAZAMIENTOS])
        minimo = vecinos.min(axis=0)
        azar = self.aleatorio.random_sample(vecinos.shape)
        direccion = xp.where(vecinos == minimo, azar, -1.0).argmax(axis=0)
        return direccion.astype(xp.int8), minimo < distancias

    def _elegir_exploracion(self, capa):
        """Explora con inercia y evita deshacer el último paso si hay otra salida."""
        xp = self.xp
        libre = (capa == VACIO) | (capa == ARENA_SECA)
        opciones = xp.stack([self.trasladar(libre, -dy, -dx, False)
                             for dy, dx in DESPLAZAMIENTOS])
        inversas = xp.asarray((1, 0, 3, 2, 7, 6, 5, 4), dtype=xp.int8)
        anterior = self.direccion_anterior
        regreso = xp.where(anterior >= 0, inversas[xp.maximum(anterior, 0)], -1)
        indices = xp.arange(8)[:, None, None]
        sin_regreso = opciones & (indices != regreso)
        opciones = xp.where(sin_regreso.any(axis=0)[None, :, :], sin_regreso, opciones)
        puntajes = self.aleatorio.random_sample(opciones.shape)
        # La dirección previa gana con frecuencia cuando aún está libre.
        mantener = self.aleatorio.random_sample(capa.shape) < 0.75
        puntajes += ((indices == anterior) & mantener) * 2.0
        return xp.where(opciones, puntajes, -1.0).argmax(axis=0).astype(xp.int8)

    def _entregar_comida(self, capa):
        for nido, reina, obrera in ((NIDO_N, REINA_N, OBRERA_N),
                                    (NIDO_R, REINA_R, OBRERA_R)):
            hogar = (capa == nido) | (capa == reina)
            entregan = ((capa == obrera) & self.carga_comida
                        & self.escanear_presencia_3x3(hogar))
            cantidad = int(self._escalar(entregan.sum()))
            self.reservas_nido[nido] += cantidad * self.valor_comida
            self.comida_entregada[nido] += cantidad
            self.carga_comida[entregan] = False
            self.pasos_con_carga[entregan] = 0

    def _dejar_rastro_de_regreso(self, comida):
        xp = self.xp
        # Solo marca quien lleva alimento. El rastro disminuye al alejarse de él.
        intensidad = xp.maximum(30, 220 - self.pasos_con_carga.astype(xp.int32) * 3)
        cargadas = self.carga_comida
        comida[cargadas] = xp.maximum(comida[cargadas], intensidad[cargadas]).astype(xp.uint8)
        self.pasos_con_carga[cargadas] = xp.minimum(
            self.pasos_con_carga[cargadas].astype(xp.int32) + 1, 65535).astype(xp.uint16)

    def aplicar_mantenimiento_nidos(self, capa):
        """Las reservas sostienen a la colonia; el hambre prolongada mata su base."""
        for nido, reina in ((NIDO_N, REINA_N), (NIDO_R, REINA_R)):
            base = (capa == nido) | (capa == reina)
            if not self._tiene(base):
                continue
            self.reservas_nido[nido] = max(0.0, self.reservas_nido[nido] - self.consumo_nido)
            if self.reservas_nido[nido] == 0:
                self.turnos_hambre[nido] += 1
            else:
                self.turnos_hambre[nido] = 0
            if self.turnos_hambre[nido] >= self.limite_hambre:
                capa[base] = CADAVER

    def estado_colonias(self):
        return {
            nombre: {"reservas": round(self.reservas_nido[nido], 3),
                     "turnos_hambre": self.turnos_hambre[nido],
                     "comida_entregada": self.comida_entregada[nido]}
            for nombre, nido in (("negra", NIDO_N), ("roja", NIDO_R))
        }


