def _a_numpy(matriz):
    """Convierte solo al serializar datos; el motor sigue operando en GPU si procede."""
    return matriz.get() if hasattr(matriz, "get") else np.asarray(matriz)


class ModoDios:
    def __init__(self):
        self._cola_acciones = deque()
        self._lock = threading.Lock()

    @staticmethod
    def _validar_coordenada(valor, nombre):
        if isinstance(valor, bool):
            raise ValueError(f"{nombre} no puede ser booleano")
        n = int(valor)
        if float(valor) != n:
            raise ValueError(f"{nombre} debe ser entero")
        return n

    @staticmethod
    def _validar_grosor(grosor):
        n = ModoDios._validar_coordenada(grosor, "grosor")
        if n < 1 or n % 2 == 0 or n > 101:
            raise ValueError("grosor debe ser impar y estar entre 1 y 101 (ej. 1, 3, 5)")
        return n

    def pintar_celda(self, fila, columna, id_pincel, grosor=1):
        """Encola pincel; NO interrumpe el ciclo de simulacion."""
        if id_pincel not in PINCELES_FISICOS and id_pincel not in PINCEL_A_CAPA:
            raise ValueError(f"id_pincel={id_pincel} no es valido")
        accion = {
            "tipo": "pintar", "fila": self._validar_coordenada(fila, "fila"),
            "columna": self._validar_coordenada(columna, "columna"),
            "id_pincel": int(id_pincel), "grosor": self._validar_grosor(grosor),
        }
        with self._lock:
            self._cola_acciones.append(accion)

    def borrar_celda(self, fila, columna, grosor=1):
        accion = {
            "tipo": "borrar", "fila": self._validar_coordenada(fila, "fila"),
            "columna": self._validar_coordenada(columna, "columna"),
            "grosor": self._validar_grosor(grosor),
        }
        with self._lock:
            self._cola_acciones.append(accion)

    @staticmethod
    def _aplicar_accion(matriz, accion, terreno_arena=None, estado_entidades=None):
        alto, ancho = matriz.shape[:2]
        # Una araña tiene un centro físico; el sprite ocupa 3x3 al dibujarla.
        es_arana = accion.get("id_pincel") == DEPREDADOR
        radio = 0 if es_arana else accion["grosor"] // 2
        y0 = max(0, accion["fila"] - radio)
        y1 = min(alto, accion["fila"] + radio + 1)
        x0 = max(0, accion["columna"] - radio)
        x1 = min(ancho, accion["columna"] + radio + 1)
        # Un pincel fuera del mundo no debe modificar accidentalmente el borde.
        if y0 >= y1 or x0 >= x1:
            return
        cambia_fisica = (accion["tipo"] == "borrar"
                         or accion.get("id_pincel") in PINCELES_FISICOS)
        if cambia_fisica and estado_entidades is not None:
            for estado, vacio in zip(estado_entidades, (False, 0, -1)):
                estado[y0:y1, x0:x1] = vacio
        if accion["tipo"] == "borrar":
            matriz[y0:y1, x0:x1, :] = 0
            if terreno_arena is not None:
                terreno_arena[y0:y1, x0:x1] = False
            return
        id_pincel = accion["id_pincel"]
        if id_pincel in PINCELES_FISICOS:
            matriz[y0:y1, x0:x1, CAPA_FISICA] = id_pincel
            if terreno_arena is not None:
                if id_pincel == ARENA_SECA:
                    terreno_arena[y0:y1, x0:x1] = True
                elif id_pincel == MURO:
                    terreno_arena[y0:y1, x0:x1] = False
            if id_pincel == MURO:
                matriz[y0:y1, x0:x1, 1:6] = 0
        else:
            capa = PINCEL_A_CAPA[id_pincel]
            # No pintar feromonas dentro de un muro.
            region = matriz[y0:y1, x0:x1, :]
            quimica = region[:, :, capa]
            quimica[region[:, :, CAPA_FISICA] != MURO] = INTENSIDAD_FEROMONA_PINCEL

    def procesar_cola_acciones(self, matriz, terreno_arena=None, estado_entidades=None):
        """Drena acciones bajo un lock y las ejecuta sobre lectura antes del tick."""
        with self._lock:
            pendientes = list(self._cola_acciones)
            self._cola_acciones.clear()
        for accion in pendientes:
            self._aplicar_accion(matriz, accion, terreno_arena, estado_entidades)
        return matriz

    @property
    def acciones_pendientes(self):
        with self._lock:
            return len(self._cola_acciones)


def obtener_estado_json(matriz, x, y, radio=5):
    """Vista de depuracion: estadisticas de todas las capas del area solicitada."""
    alto, ancho = matriz.shape[:2]
    y = max(0, min(alto-1, int(y)))
    x = max(0, min(ancho-1, int(x)))
    radio = max(0, int(radio))
    y0, y1 = max(0, y-radio), min(alto, y+radio+1)
    x0, x1 = max(0, x-radio), min(ancho, x+radio+1)
    region = _a_numpy(matriz[y0:y1, x0:x1, :])
    centro = _a_numpy(matriz[y, x, :])
    unicos, cantidades = np.unique(region[:, :, CAPA_FISICA], return_counts=True)
    capas = {
        nombre: float(centro[indice])
        for indice, nombre in NOMBRES_CAPAS.items()
    }
    conteo = {
        NOMBRES_ESTADOS.get(int(codigo), f"desconocido_{int(codigo)}"): int(cant)
        for codigo, cant in zip(unicos, cantidades)
    }
    prom = {NOMBRES_CAPAS[i]: float(region[:, :, i].mean()) for i in range(1, 6)}
    maximos = {NOMBRES_CAPAS[i]: int(region[:, :, i].max()) for i in range(1, 6)}
    activas = {NOMBRES_CAPAS[i]: int(np.count_nonzero(region[:, :, i])) for i in range(1, 6)}
    return {
        "coordenadas": {"x": x, "y": y}, "centro": capas,
        "region": {"tamano": f"{y1-y0}x{x1-x0}", "conteo_estados": conteo,
                   "promedios_feromonas": prom, "maximos_feromonas": maximos,
                   "celdas_feromona_activas": activas},
    }


def obtener_mapa_completo(matriz, capa=CAPA_FISICA, paso=1):
    """Retorna lista plana de una capa para el frontend (0=fisica; 1..5=olores).

    Antes la API devolvia solamente la fisica y ocultaba el rastro y la alarma.
    `paso` permite muestrear una cuadricula grande sin transmitir tanto JSON.
    """
    capa = int(capa)
    paso = int(paso)
    if capa not in NOMBRES_CAPAS or paso < 1:
        raise ValueError("capa debe estar entre 0 y 5 y paso debe ser >=1")
    return _a_numpy(matriz[::paso, ::paso, capa]).astype(np.uint8).ravel().tolist()


def obtener_vista_capas(matriz, capas=(0, 1, 2, 3, 4, 5), paso=1):
    """Seis capas y centros de arañas; el frontend dibuja cada sprite en 3x3.

    Las coordenadas de los sprites se expresan en celdas de la vista muestreada.
    La matriz física mantiene una sola entidad por araña.
    """
    alto, ancho = matriz.shape[:2]
    paso = int(paso)
    if paso < 1:
        raise ValueError("paso debe ser >=1")
    return {
        "alto": (alto + paso - 1) // paso,
        "ancho": (ancho + paso - 1) // paso,
        "sprites": {"depredador": {"alto": 3, "ancho": 3, "anclaje": "centro"}},
        "depredadores": [{"fila": int(y) // paso, "columna": int(x) // paso}
                         for y, x in np.argwhere(_a_numpy(matriz[:, :, 0]) == DEPREDADOR)],
        "capas": {NOMBRES_CAPAS[int(i)]: obtener_mapa_completo(matriz, i, paso)
                  for i in capas},
    }


