PASOS_DIFUSION = 2
PERDIDA_EVAPORACION = 2
PROB_ATAQUE_DEPREDADOR = 0.35
MIN_SOLDADOS_CONTRA_ARANA = 4
RADIO_BUSQUEDA_COMIDA = 16
RESERVA_INICIAL = 100.0
CONSUMO_NIDO = 0.2
VALOR_COMIDA = 20.0
COSTO_NACIMIENTO = 5.0
