def mapa_laberinto_numpy(alto=25, ancho=41, semilla_mapa=7):
    """Escenario de prueba DFS con depredador movil."""
    if alto % 2 == 0 or ancho % 2 == 0 or alto < 9 or ancho < 9:
        raise ValueError("Para el laberinto usar dimensiones impares >=9.")
    rs = np.random.RandomState(semilla_mapa)
    t = crear_tensor_numpy(alto, ancho, marco=False)
    t[:, :, 0] = MURO
    pila = [(1, 1)]
    t[1, 1, 0] = VACIO
    while pila:
        y, x = pila[-1]
        vec = [(y+dy,x+dx,dy,dx) for dy,dx in ((-2,0),(2,0),(0,-2),(0,2))
               if 0 < y+dy < alto-1 and 0 < x+dx < ancho-1 and t[y+dy,x+dx,0] == MURO]
        if not vec:
            pila.pop()
            continue
        ny, nx, dy, dx = vec[rs.randint(len(vec))]
        t[y+dy//2, x+dx//2, 0] = VACIO
        t[ny, nx, 0] = VACIO
        pila.append((ny, nx))
    t[1:4, 1:4, 0] = VACIO
    colocar_numpy(t, 1, 1, REINA_N)
    colocar_numpy(t, 2, 2, NIDO_N)
    for y, x in ((alto-2, ancho-2), (alto-2, ancho-4)):
        t[y, x, 0] = COMIDA
    libres = np.argwhere(t[:, :, 0] == VACIO)
    medio = np.abs(libres[:,0] - alto//2) + np.abs(libres[:,1] - ancho//2)
    y, x = libres[np.argmin(medio)]
    colocar_numpy(t, y, x, DEPREDADOR)
    for k in (0.3, 0.6):
        y, x = libres[int(len(libres)*k)]
        t[y,x,0] = VENENO
    return t


